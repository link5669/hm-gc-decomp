#!/usr/bin/env python3
"""Generate src/mp/font.h: an 8x12 1-bit font (ASCII 32..126) rendered from DejaVu Sans Mono Bold
(Bitstream Vera / DejaVu font license, permissive)."""
from PIL import Image, ImageDraw, ImageFont
import sys
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
W, H = 8, 12
f = ImageFont.truetype(FONT, 11)
out = ["/* generated by tools/mp/genfont.py from DejaVu Sans Mono Bold; 8x12, MSB = left pixel */",
       "#define MP_FONT_W 8", "#define MP_FONT_H 12", "static const unsigned char mp_font[95][12] = {"]
for c in range(32, 127):
    im = Image.new("L", (W, H), 0)
    ImageDraw.Draw(im).text((0, -1), chr(c), font=f, fill=255)
    rows = []
    for y in range(H):
        b = 0
        for x in range(W):
            if im.getpixel((x, y)) > 110:
                b |= 0x80 >> x
        rows.append(b)
    out.append("    {" + ",".join(f"0x{r:02x}" for r in rows) + "}, /* " + (repr(chr(c)) if c != 92 else "backslash") + " */")
out.append("};")
open(sys.argv[1] if len(sys.argv) > 1 else "src/mp/font.h", "w").write("\n".join(out) + "\n")
